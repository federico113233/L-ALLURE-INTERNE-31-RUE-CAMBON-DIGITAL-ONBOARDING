// Compiles knowledge/chanel_rag_knowledge_base.md into a typed module that the
// API routes inject into every Claude call (the RAG "source of truth").
// Runs automatically before `dev` and `build`.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "knowledge", "chanel_rag_knowledge_base.md");
const out = join(root, "lib", "knowledge", "kb.generated.ts");

const raw = readFileSync(src, "utf8");

// The source was exported from Google Docs: markdown control characters are
// backslash-escaped (\#, \*, \-, \|, \[ ...). Strip the escapes.
const clean = raw
  .replace(/\r\n/g, "\n")
  .replace(/\\([#*\-_\[\]>|`.!+()=])/g, "$1")
  .replace(/[ \t]+\n/g, "\n")
  .trim();

// Split into top-level sections ("## 1. ...") so prompts can cite them.
const sections = [];
let current = null;
for (const line of clean.split("\n")) {
  const m = /^##\s+(\d+)\.\s*(.+)$/.exec(line);
  if (m) {
    current = { id: `S${m[1]}`, title: m[2].trim(), body: "" };
    sections.push(current);
  } else if (current) {
    current.body += line + "\n";
  }
}
for (const s of sections) s.body = s.body.trim();

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/build-kb.mjs from knowledge/chanel_rag_knowledge_base.md — do not edit.\n` +
    `export const KB_TEXT: string = ${JSON.stringify(clean)};\n\n` +
    `export const KB_SECTIONS: { id: string; title: string; body: string }[] = ${JSON.stringify(sections, null, 2)};\n`,
);
console.log(`[kb] ${sections.length} sections, ${clean.length} chars -> lib/knowledge/kb.generated.ts`);
